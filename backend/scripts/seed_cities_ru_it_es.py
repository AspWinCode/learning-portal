def run() -> None:
    db = SessionLocal()

    all_cities = RUSSIA + ITALY + SPAIN
    added, skipped = 0, 0
    try:
        for name in all_cities:
            name = name.strip()
            exists = (
                db.query(SalesCity)
                .filter(cast(SalesCity.name, Text).ilike(name))
                .first()
            )
            if exists:
                skipped += 1
                continue
            db.add(SalesCity(name=name, is_active=True))
            added += 1
        db.commit()
    finally:
        db.close()

    print(f"Добавлено: {added}, пропущено (уже было): {skipped}")


if __name__ == "__main__":
    run()
